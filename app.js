function setLanguage(lang) {
  currentLanguage = lang;
  document.documentElement.lang = lang;
  elements.forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[lang][key]) {
      element.textContent = dictionary[lang][key];
    }
  });
  placeholderElements.forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (dictionary[lang][key]) {
      element.placeholder = dictionary[lang][key];
    }
  });
  buttons.forEach((button) => {
    button.classList.toggle("active", button.dataset.lang === lang);
  });
  if (languageMeta[lang]) {
    languageCode.textContent = languageMeta[lang].code;
    languageName.textContent = languageMeta[lang].name;
  }
  languageSwitch?.classList.remove("open");
  languageTrigger?.setAttribute("aria-expanded", "false");
  syncEnhancedSelectLabels();
}

