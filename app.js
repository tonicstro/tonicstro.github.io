const motionEnabled = !window.matchMedia("(prefers-reduced-motion: reduce)").matches;

if (motionEnabled) {
  const interactiveCards = document.querySelectorAll(
    ".signal-row div, .service-card, .timeline article, .usecase-list article, .control-grid div, .diagnostic-form"
  );
  const revealTargets = document.querySelectorAll(
    ".logo-band, .section-heading, .service-card, .timeline article, .split-section > *, .control-grid div, .diagnostic-section"
  );
  const systemVisual = document.querySelector(".system-visual");

  let pointerFrame = null;

  window.addEventListener("pointermove", (event) => {
    if (pointerFrame) return;
    pointerFrame = window.requestAnimationFrame(() => {
      document.documentElement.style.setProperty("--mouse-x", `${event.clientX}px`);
      document.documentElement.style.setProperty("--mouse-y", `${event.clientY}px`);
      pointerFrame = null;
    });
  });

  interactiveCards.forEach((card) => {
    card.addEventListener("pointermove", (event) => {
      const rect = card.getBoundingClientRect();
      const x = ((event.clientX - rect.left) / rect.width) * 100;
      const y = ((event.clientY - rect.top) / rect.height) * 100;
      card.style.setProperty("--card-x", `${x}%`);
      card.style.setProperty("--card-y", `${y}%`);
    });
  });

  if (systemVisual) {
    systemVisual.addEventListener("pointermove", (event) => {
      const rect = systemVisual.getBoundingClientRect();
      const x = (event.clientX - rect.left) / rect.width - 0.5;
      const y = (event.clientY - rect.top) / rect.height - 0.5;
      systemVisual.style.transform = `perspective(900px) rotateX(${y * -4}deg) rotateY(${x * 5}deg) translateY(-4px)`;
    });

    systemVisual.addEventListener("pointerleave", () => {
      systemVisual.style.transform = "";
    });
  }

  revealTargets.forEach((target) => target.classList.add("reveal"));

  const revealObserver = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        revealObserver.unobserve(entry.target);
      }
    });
  }, { threshold: 0.16 });

  revealTargets.forEach((target) => revealObserver.observe(target));
}
